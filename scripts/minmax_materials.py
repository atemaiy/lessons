def build_pdf():
    from reportlab.pdfgen import canvas
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Preformatted, Table, TableStyle, PageBreak
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib import colors
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.lib.pagesizes import A4
    font_dir = Path('C:/Windows/Fonts')
    for name, filename in [('Body','arial.ttf'),('Bold','arialbd.ttf'),('Mono','consola.ttf')]:
        pdfmetrics.registerFont(TTFont(name, str(font_dir / filename)))
    ink = colors.HexColor('#18213c')
    violet = colors.HexColor('#5944bd')
    styles = {
        'title': ParagraphStyle('title', fontName='Bold', fontSize=25, leading=30, textColor=ink, spaceAfter=16),
        'h': ParagraphStyle('h', fontName='Bold', fontSize=12, leading=16, textColor=violet, spaceBefore=12, spaceAfter=6),
        'body': ParagraphStyle('body', fontName='Body', fontSize=10.5, leading=15, textColor=ink, spaceAfter=8),
        'small': ParagraphStyle('small', fontName='Body', fontSize=9, leading=12, textColor=ink),
        'code': ParagraphStyle('code', fontName='Mono', fontSize=10.5, leading=13, textColor=ink, backColor=colors.HexColor('#f1f3f9'), borderPadding=10, spaceBefore=8, spaceAfter=10),
    }
    def p(s, kind='body'):
        return Paragraph(escape(s).replace('\n','<br/>'), styles[kind])
    def table(rows, widths):
        obj = Table([[p(str(c),'small') for c in row] for row in rows], colWidths=widths, hAlign='LEFT')
        obj.setStyle(TableStyle([
            ('BACKGROUND',(0,0),(-1,0),colors.HexColor('#e9e5fa')),
            ('VALIGN',(0,0),(-1,-1),'TOP'),('LEFTPADDING',(0,0),(-1,-1),8),
            ('RIGHTPADDING',(0,0),(-1,-1),8),('TOPPADDING',(0,0),(-1,-1),6),('BOTTOMPADDING',(0,0),(-1,-1),6),
            ('LINEBELOW',(0,0),(-1,-1),.4,colors.HexColor('#dfe2ec')),
        ]))
        return obj
    story = [p('Решения задач по min и max','title'), p('Python • 6–8 классы • Материал для преподавателя'),
        p('Переменные и цикл while'),
        p('Здесь собраны решения девяти задач урока и домашнего задания Д1. Для каждой задачи приведены условие, идея алгоритма, рабочий код, тесты и типичная ошибка. Готовые решения открывайте после самостоятельной попытки ученика.'),
        p('Правила ввода и ограничения','h'),
        p('Каждый input() читает одно целое число с отдельной строки. В таблицах тестов числа записаны через запятую для компактности; при запуске вводите их по строкам. Приглашения к вводу в коде отсутствуют.'),
        p('№ 1 читает ровно три числа, включая возможный ноль. В № 2–9 и Д1 первый 0 завершает поток и не является данными. Непустота гарантирована условием; в № 7–8 гарантированы минимум два числа. Натуральные числа здесь положительные.'),
        p('Код рассчитан на корректный ввод по условию. Первый 0 в задачах о непустом потоке находится вне условия: у пустого набора нет минимума и максимума. Его нельзя засчитывать как корректный тест с ответом 0 0. Для отдельной версии с проверкой ввода сначала обработайте x == 0 сообщением «Нет данных», а поиск выполняйте только в другой ветке.'),
        p('Как засчитать основной маршрут','h'),
        p('Цель: каждый самостоятельно решает № 1–4. Для № 4 проверьте все шесть тестов на странице 5, начальное значение из первого элемента, исключение сигнала 0, один проход и порядок вывода. Затем попросите объяснить, что хранят mn и mx после очередного шага.'),
        p('Навигация','h'),
        table([['Материал','Страницы'],['№ 1–4 · основной маршрут','2–5'],['№ 5–7 · дальнейшее продвижение','6–8'],['№ 8–9 · буфер','9–10'],['Д1 · домашнее задание','11']], [340,159]),
        p('Все алгоритмы используют постоянное число переменных, без списков и встроенных min(), max(), sorted(). Потоковые решения читают данные один раз: время O(n), дополнительная память O(1).','small'),
        p('Основа: «План_урока_Полищук_MIN-MAX.pdf», с. 1–4; knowledge-base/baza_znaniy_prepodavatelya.md; knowledge-base/podacha_teorii.md. Условия и шкала взяты из плана; пояснения, решения и дополнительные тесты подготовлены к уроку.','small')]
    for t in TASKS + [HOME]:
        story += [PageBreak(),p(f"{t['id']}  {t['title']}",'title'),p(t['text']),p('Идея решения','h'),p(t['explanation']),Preformatted(t['code'],styles['code']),p('Проверка','h')]
        rows = [['Ввод по одному числу на строке','Ожидаемый вывод']]
        rows += [[', '.join(map(str,a)),b] for a,b in t['tests']]
        story += [table(rows,[359,140]),p('Частая ошибка','h'),p(t['error'])]
    out = ROOT/'output/pdf/minmax-solutions.pdf'
    out.parent.mkdir(parents=True,exist_ok=True)
    def footer(c,doc):
        c.setFont('Body',8)
        c.setFillColor(colors.HexColor('#66708a'))
        c.drawString(48,27,'MIN / MAX  •  Решения для преподавателя')
        c.drawRightString(A4[0]-48,27,str(doc.page))
    SimpleDocTemplate(str(out),pagesize=A4,rightMargin=48,leftMargin=48,topMargin=42,bottomMargin=45,
                      title='Решения задач по min и max',author='Материалы урока').build(story,onFirstPage=footer,onLaterPages=footer)
    print(out)

